function getLang() {
  try { return localStorage.getItem('jushqin_lang') || 'uz'; } catch (e) { return 'uz'; }
}

function setLang(lang) {
  if (!I18N[lang]) lang = 'uz';
  try { localStorage.setItem('jushqin_lang', lang); } catch (e) {}
  document.documentElement.setAttribute('lang', lang === 'uz' ? 'uz' : lang);
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N.uz && I18N.uz[key]) || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  // Profile-driven fields — use translations for public display
  const map = {
    name: 'p_name',
    title: 'p_title',
    heroHeadline: 'p_heroHeadline',
    heroSubtitle: 'p_heroSubtitle',
    intro: 'p_intro',
    bio: 'p_bio',
    story: 'p_story',
    journey: 'p_journey',
    goals: 'p_goals',
    philosophy: 'p_philosophy'
  };
  Object.keys(map).forEach(field => {
    document.querySelectorAll('[data-profile="' + field + '"]').forEach(el => {
      if (el.tagName === 'A') return;
      el.textContent = t(map[field]);
    });
  });

  // Interests
  const interestsList = document.getElementById('interests-list');
  if (interestsList) {
    interestsList.innerHTML = [1,2,3,4,5].map(i =>
      '<span class="interest-tag">' + t('p_interest' + i) + '</span>'
    ).join('');
  }

  // Timeline texts
  document.querySelectorAll('[data-i18n-tl]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n-tl'));
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === getLang());
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const lang = getLang();
  document.documentElement.setAttribute('lang', lang === 'uz' ? 'uz' : lang);
  applyI18n();
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLang(btn.dataset.lang);
    });
  });
});

window.t = t;
window.setLang = setLang;
window.getLang = getLang;
window.applyI18n = applyI18n;
